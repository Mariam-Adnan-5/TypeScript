// Use console.log() to print a value or variable to the console.
console.log("Mariam Adnan Thabet");

// Use const to declare a variable whose value will not be reassigned.
const greeting = "hello";
console.log(greeting);

// Use let to declare variables whose values can be changed later.
let firstname="Mariam";
let lastname="Thabet";

// var       → Function Scope
// let       → Block Scope
// const     → Block Scope

// Concatenate strings and variables using the + operator.
console.log('firstname : '+firstname);
lastname="Adnan";

// Use template literals to insert variables directly into a string.
console.log(`lastname : ${lastname}`);

// when we try to create a var 
// decleration => initialization 

let age ; // variable declaraton without initialization

console.log(age); //  output is undefined

age =22;// var initialization
